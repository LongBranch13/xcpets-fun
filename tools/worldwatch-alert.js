#!/usr/bin/env node
/* World watch alerts (Nov 22 2026). Reads the findings tools/worldwatch.js wrote and keeps one GitHub issue labelled world-alert:
 * opens it on a problem, comments at most every 2 hours while it lasts (or sooner when the problem changes), closes it when fine.
 * When TELEGRAM_BOT_TOKEN and TELEGRAM_ALERT_CHAT_ID are set, the same alert and the all clear go to that Telegram chat. */
'use strict';
const fs = require('fs');
const REPO = process.env.GITHUB_REPOSITORY, TOKEN = process.env.GH_TOKEN, RUN = process.env.RUN_URL || '';
const r = (() => { try { return JSON.parse(fs.readFileSync(process.argv[2], 'utf8')); } catch (e) { return { problems: ['World watch itself failed to run.'], notes: [] }; } })();
const bad = r.problems && r.problems.length > 0;
async function gh(p, o) {
  const res = await fetch('https://api.github.com/repos/' + REPO + p, Object.assign({ headers: { Authorization: 'Bearer ' + TOKEN, Accept: 'application/vnd.github+json', 'Content-Type': 'application/json', 'User-Agent': 'xcpets-worldwatch' } }, o || {}));
  if (!res.ok) throw new Error(p.split('?')[0] + ' ' + res.status);
  return res.status === 204 ? null : res.json();
}
async function telegram(text) {
  const t = process.env.TELEGRAM_BOT_TOKEN, chat = process.env.TELEGRAM_ALERT_CHAT_ID;
  if (!t || !chat) return;
  try { await fetch('https://api.telegram.org/bot' + t + '/sendMessage', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ chat_id: chat, text: text, disable_web_page_preview: true }) }); }
  catch (e) { console.log('telegram: not sent'); }
}
const FOOT = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
(async () => {
  if (!REPO || !TOKEN) { console.log('no GitHub token: report only'); return; }
  const open = (await gh('/issues?state=open&labels=world-alert&per_page=5')).filter(i => !i.pull_request)[0] || null;
  const what = (r.problems || []).map(p => '- ' + p).join('\n');
  const facts = 'Chain tip ' + (r.chainTip || '?') + ', world players use ' + (r.worldTip || 'none') + ', live rules ' + (r.liveRsig || '?') + ', main rules ' + (r.mainRsig || '?') + '.';
  if (bad) {
    const body = what + '\n\n' + facts + (r.notes && r.notes.length ? '\n\n' + r.notes.map(n => '- ' + n).join('\n') : '') + '\n\nRun: ' + RUN +
      '\n\nWhat usually fixes it: Actions > server-repair (type REPAIR, diagnose_only first). This issue closes by itself when the fast load works again.' + FOOT;
    if (!open) {
      try { await gh('/labels', { method: 'POST', body: JSON.stringify({ name: 'world-alert', color: 'd93f0b', description: 'World watch: players get the slow load' }) }); } catch (e) {}
      await gh('/issues', { method: 'POST', body: JSON.stringify({ title: 'World watch: players may get the slow load', body: body, labels: ['world-alert'] }) });
      await telegram('⚠️ XCPETS world watch: players may get the slow load.\n' + (r.problems || []).join('\n') + '\n' + RUN);
      console.log('opened a world-alert issue');
    } else {
      const comments = await gh('/issues/' + open.number + '/comments?per_page=100');
      const last = comments.length ? comments[comments.length - 1] : null, lastAt = Date.parse(last ? last.created_at : open.created_at);
      const sameProblem = (last ? last.body : open.body).indexOf(what) === 0;
      if (!sameProblem || Date.now() - lastAt > 2 * 3600 * 1000) {
        await gh('/issues/' + open.number + '/comments', { method: 'POST', body: JSON.stringify({ body: 'Still happening.\n\n' + body }) });
        if (!sameProblem) await telegram('⚠️ XCPETS world watch, changed:\n' + (r.problems || []).join('\n') + '\n' + RUN);
        console.log('commented on #' + open.number);
      } else console.log('still open as #' + open.number + ', no new comment yet');
    }
  } else if (open) {
    await gh('/issues/' + open.number + '/comments', { method: 'POST', body: JSON.stringify({ body: 'Fine again: players get the fast load. ' + facts + '\n\nRun: ' + RUN + FOOT }) });
    await gh('/issues/' + open.number, { method: 'PATCH', body: JSON.stringify({ state: 'closed', state_reason: 'completed' }) });
    await telegram('✅ XCPETS world watch: fast load works again. ' + facts);
    console.log('closed #' + open.number);
  } else console.log('fine, no open alert');
})().catch(e => { console.log('alert step failed: ' + e.message); process.exit(1); });
